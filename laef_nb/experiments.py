from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd
import yaml

from . import config as C
from .config import Study
from .shell import run

HEADER = """# Generated by laef_nb.experiments.write_yaml. Edit the Study in the notebook, not this file.
# One pair of sections per thread count, so results land in results/{name}/c<threads>/.
# rho is a multiple of mu_sat(C) from data/artifacts/<dataset>/profile/profile_C<threads>.json,
# so every thread count is loaded relative to its own measured capacity.
"""


def _workload(study: Study) -> dict:
    return {"profile": study.arrival, "rho": list(study.rhos), "duration_s": study.duration_s}


def spec(study: Study) -> dict:
    if study.arrival not in C.ARRIVALS:
        raise ValueError(f"arrival must be one of {C.ARRIVALS}, got {study.arrival!r}. "
                         "The step, mmpp2 and trace profiles were removed from the engine.")
    out: dict[str, dict] = {}
    for t in study.threads:
        out[f"c{t}_ada"] = {
            "name": f"{study.name}/c{t}/ada",
            "datasets": list(study.datasets),
            "threads": [t],
            "policies": [C.BASELINE_POLICY],
            "slo": {"fraction": [1.0]},
            "workloads": [_workload(study)],
            "repeats": study.repeats,
        }
        out[f"c{t}_laef"] = {
            "name": f"{study.name}/c{t}/laef",
            "datasets": list(study.datasets),
            "threads": [t],
            "policies": list(study.la_policies),
            "slo": {"fraction": list(study.slo_fractions)},
            "workloads": [_workload(study)],
            "repeats": study.repeats,
        }
    return out


def write_yaml(study: Study) -> Path:
    study.yaml_path.parent.mkdir(parents=True, exist_ok=True)
    study.yaml_path.write_text(HEADER.format(name=study.name) + yaml.safe_dump(spec(study), sort_keys=False),
                               encoding="utf-8")
    return study.yaml_path


def plan(study: Study) -> pd.DataFrame:
    rows = []
    for t in study.threads:
        for ds in study.datasets:
            for rho in study.rhos:
                rows.append({"threads": t, "dataset": ds, "rho": rho,
                             "policy": C.BASELINE_POLICY, "slo_fraction": 1.0})
                for pol in study.la_policies:
                    for f in study.slo_fractions:
                        rows.append({"threads": t, "dataset": ds, "rho": rho,
                                     "policy": pol, "slo_fraction": f})
    df = pd.DataFrame(rows)
    return pd.concat([df] * study.repeats, ignore_index=True)


def stale(study: Study) -> pd.DataFrame:
    """Finished runs whose duration or arrival process no longer matches the Study."""
    rows = []
    for d in sorted(p.parent for p in study.dir.rglob("summary.json")) if study.dir.exists() else []:
        cfg_path = d / "run_config.json"
        if not cfg_path.exists():
            continue
        wl = json.loads(cfg_path.read_text(encoding="utf-8")).get("workload", {})
        got_d, got_p = wl.get("duration_s"), wl.get("profile")
        if (got_d is not None and abs(float(got_d) - study.duration_s) > 1e-6) or got_p != study.arrival:
            rows.append({"run_id": d.name, "duration_s": got_d, "want_duration_s": study.duration_s,
                         "profile": got_p, "want_profile": study.arrival})
    return pd.DataFrame(rows)


def pending(study: Study) -> pd.DataFrame:
    old = stale(study)
    bad = set(old.run_id) if not old.empty else set()
    rows = []
    for t in study.threads:
        d = study.thread_dir(t)
        started = {p.parent.name for p in d.rglob("run_meta.json")} if d.exists() else set()
        finished = {p.parent.name for p in d.rglob("summary.json")} if d.exists() else set()
        rows.append({"threads": t, "expected": study.runs_per_thread, "finished": len(finished),
                     "incomplete": len(started - finished), "stale": len(finished & bad)})
    return pd.DataFrame(rows)


def launch(study: Study, interval: float = 1.0, keep_queries: bool = False,
           dry_run: bool = False, force: bool = False) -> int:
    write_yaml(study)
    if dry_run:
        return run([sys.executable, "-u", str(C.SCRIPTS / "run_experiments.py"),
                    str(study.yaml_path), "--dry-run"], check=False)
    old = stale(study)
    if not old.empty and not force:
        print(f"warning: {len(old)} finished runs do not match this Study and will be reused as they are. "
              "Pass force=True to rerun them.", flush=True)
    return run([sys.executable, "-u", str(C.SCRIPTS / "run_slo_study.py"),
                "--experiment", str(study.yaml_path), "--interval", str(interval)]
               + (["--keep-queries"] if keep_queries else [])
               + (["--force"] if force else []), check=False)


def check_ready(study: Study) -> list[str]:
    problems = []
    for ds in study.datasets:
        base = C.ARTIFACTS / ds
        for rel in C.DATASET_INPUTS:
            if not (base / rel).exists():
                problems.append(f"{ds}: missing {rel}")
        for t in study.threads:
            if not (base / "profile" / f"profile_C{t}.json").exists():
                problems.append(f"{ds}: missing profile_C{t}.json")
    return problems
